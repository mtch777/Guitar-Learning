"""Package the existing three authored recipes for browser execution.

Only the existing composition functions and seven tiny selected ingredients are
distributed. Corpus scores, observations, annotations, source identity bindings,
and the full vocabulary remain private. This does not rerun source selection.

Acceptance checklist (verified by test_riff_browser.py):
- Extract existing core verbatim, with its source digest retained.
- Preserve all six earlier baseline/variation scores exactly at default tempos.
- Expose only recipe and tempo, with deterministic generation and valid inputs.
- Ship minimal ingredients without private source metadata.

Run this packager only in the research checkout; the deployed Python module has
no dependency on research files and performs no filesystem writes.
"""
