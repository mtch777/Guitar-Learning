import json

TUNING = [64, 59, 55, 50, 45, 40, 35, 28]

def frac(value):
    return F(str(value))

def notation(q):
    d=q/4
    for kind in (1,2,4,8,16,32,64):
        for dots in (0,1,2):
            if F(1,kind)*(2-F(1,2**dots))==d:
                return dict(duration=[d.numerator,d.denominator],type=kind,**({'dots':dots} if dots else {}))
    raise ValueError(f'No exact ordinary notation for {q} quarters')

def split_duration(q):
    choices=[F(4),F(3),F(2),F(3,2),F(1),F(3,4),F(1,2),F(1,4)]
    result=[]
    while q:
        size=next((v for v in choices if v<=q),None)
        if size is None: raise ValueError(f'Off-grid remainder {q}')
        result.append(size);q-=size
    return result

def candidate_events(candidate, scale=F(1), shift=0):
    """Uniform timing scaling and fixed-open/fretted translation are explicit."""
    out=[]
    for e in candidate['events']:
        notes=[]
        for n in e['notes']:
            fret=n['fret']+(shift if n['fret'] else 0)
            if not 0<=fret<=24:raise ValueError('Translated contact outside fretboard')
            notes.append(dict(string=n['string']-1,fret=fret,pitch=TUNING[n['string']-1]+fret,
                              source_id=n.get('source_id')))
        durations=[frac(n['duration_q'])*scale for n in e['notes']]
        if len(set(durations))!=1:raise ValueError('Unequal coattack holds need explicit voice/tie authoring')
        onset=frac(e['relative_onset_q'])*scale
        dur=durations[0]
        if (onset*4).denominator!=1 or (dur*4).denominator!=1:raise ValueError('Not a sixteenth-grid writing candidate')
        out.append(dict(onset=onset,duration=dur,notes=notes))
    return out

def realization_summary(events):
    pitches=[[n['pitch'] for n in e['notes']] for e in events]
    single=all(len(p)==1 for p in pitches)
    return dict(pitches=pitches,intervals=[b[0]-a[0] for a,b in zip(pitches,pitches[1:])] if single else None,
                chord_spacings=[[p-min(ps) for p in sorted(ps)] for ps in pitches],
                onsets_q=[str(e['onset']) for e in events],durations_q=[str(e['duration']) for e in events],
                contacts=[[[n['string']+1,n['fret']] for n in e['notes']] for e in events])

class Phrase:
    def __init__(self,tempo):
        self.tempo=tempo;self.events=[];self.gestures=[]

    def add(self,identity,candidate,at,*,scale=1,shift=0,role='answer',mute=False,
            prefix=None,duration=None,retime=None,order=None,legato=True,accent=True):
        events=candidate_events(candidate,frac(scale),shift)
        if order is not None:
            original=deepcopy(events)
            assert len(order)==len(events) and all(0<=i<len(events) for i in order)
            for slot,i in enumerate(order):events[slot]['notes']=deepcopy(original[i]['notes'])
        if prefix is not None:events=events[:prefix]
        if retime:
            # Explicit alternative clock: slots retain corresponding attack identities.
            assert len(retime)==len(events)
            for e,(on,dur) in zip(events,retime):e['onset']=frac(on);e['duration']=frac(dur)
        if duration is not None:
            assert len(events)==1
            events[0]['duration']=frac(duration)
        before=realization_summary(candidate_events(candidate))
        summary=realization_summary(events)
        for i,e in enumerate(events):
            e['at']=frac(at)+e.pop('onset');e['identity']=f'{identity}:a{i}'
            e['role']=role;e['mute']=mute;e['velocity']='f' if i==0 else 'mf'
            e['accent']=bool(accent and i==0);e['legato']=legato
            self.events.append(e)
        self.gestures.append(dict(id=identity,role=role,at_q=str(at),candidate_id=candidate['id'],
            source=candidate['source'],source_material=before,realized_material=summary,
            transform=dict(time_scale=str(scale),fretted_shift=shift,prefix=prefix,retime=retime,order=order,hold=str(duration) if duration is not None else None),
            source_shape_family=candidate.get('shape_family'),hotspot_support=candidate.get('hotspot_support'),
            selection=candidate.get('selection',candidate.get('score_breakdown'))))
        return self

    def score(self):
        events=deepcopy(sorted(self.events,key=lambda e:e['at']))
        assert events and events[0]['at']>=0
        for left,right in zip(events,events[1:]):
            assert left['at']+left['duration']<=right['at'],('Authored overlap',left['identity'],right['identity'])
        assert events[-1]['at']+events[-1]['duration']<=32
        # HP is an authored execution choice only for an adjacent same-string
        # arrival, with a bounded reach. No cross-string or rest-spanning HP.
        for i,e in enumerate(events):
            for n in e['notes']:n['hp']=False
            if i+1<len(events) and e['legato'] and not e['mute']:
                nxt=events[i+1]
                if len(e['notes'])==len(nxt['notes'])==1 and e['at']+e['duration']==nxt['at']:
                    a,b=e['notes'][0],nxt['notes'][0]
                    reachable=0<abs(a['fret']-b['fret']) and (abs(a['fret']-b['fret'])<=5 or b['fret']==0)
                    if a['string']==b['string'] and reachable and nxt['legato'] and not nxt['mute']:
                        a['hp']=True
        bars=[[] for _ in range(8)];rows=[]
        cursor=F(0)
        def silence(end):
            nonlocal cursor
            while cursor<end:
                boundary=(cursor//4+1)*4
                for length in split_duration(min(end,boundary)-cursor):
                    bars[int(cursor//4)].append(dict(**notation(length),notes=[],rest=True,_role='breath'))
                    cursor+=length
        for e in events:
            silence(e['at'])
            assert cursor==e['at']
            end=cursor+e['duration']
            if end>(cursor//4+1)*4:raise ValueError(f"Cross-bar hold needs tie authoring: {e['identity']}")
            bar=int(cursor//4);bi=len(bars[bar]);rawnotes=[]
            assert len({n['string'] for n in e['notes']})==len(e['notes'])
            frets=[n['fret'] for n in e['notes'] if n['fret']]
            assert not frets or max(frets)-min(frets)<=5,('Chord span',e['identity'])
            for ni,n in enumerate(e['notes']):
                note=dict(string=n['string'],fret=n['fret'])
                if n['hp']:note['hp']=True
                if e['accent']:note['accentuated']=1
                rawnotes.append(note)
                rows.append(dict(id=f"{e['identity']}:n{ni}",bar=bar+1,beat=bi,onset_q=str(cursor),duration_q=str(e['duration']),
                    string=n['string'],string_number=n['string']+1,fret=n['fret'],pitch=n['pitch'],role=e['role'],
                    palm_mute=e['mute'],accent=e['accent'],hp=n['hp'],velocity=e['velocity']))
            bars[bar].append(dict(**notation(e['duration']),notes=rawnotes,velocity=e['velocity'],
                **({'palmMute':True} if e['mute'] else {}),_role=e['role']))
            cursor=end
        silence(F(32))
        assert all(sum((F(*b['duration']) for b in bar),F(0))==1 for bar in bars)
        return dict(tuning_high_to_low=TUNING,tempo=self.tempo,meter=[4,4],bars=bars,notes=rows)

def final_differences(a,b):
    aa={n['id']:n for n in a['notes']};bb={n['id']:n for n in b['notes']}
    shared=aa.keys()&bb.keys()
    changed={field:[i for i in sorted(shared) if aa[i][field]!=bb[i][field]] for field in
        ('pitch','onset_q','duration_q','fret','string','hp','palm_mute','velocity','accent')}
    return dict(shared=len(shared),added=sorted(bb.keys()-aa.keys()),removed=sorted(aa.keys()-bb.keys()),changed=changed)

def build_conversation(m,variant=False):
    p=Phrase(142);g=m['hook'];a=m['middle'];h=m['high'];c=m['open_chord']
    # Slots are a composed sentence; the note/contact/time content comes from the selected joint candidates.
    for slot,at in [('call1',0),('call2',6),('call3',8),('call5',F(69,4)),('call6',F(89,4)),('call7',24)]:
        p.add(slot,g,at,role='low rhythmic call',mute=True)
    for slot,at in [('answer1',2),('answer3',10),('answer4',F(57,4)),('answer5',16),('answer7',26),('answer8',F(119,4))]:
        shift=5 if variant and slot in ('answer3','answer7','answer8') else 0
        p.add(slot,a,at,shift=shift,role='open E and moving upper answer')
    for slot,at in [('crest2',4),('crest4',F(49,4)),('crest6',F(41,2)),('crest8',28)]:
        retime=[['0','1/4'],['1/4','1/2'],['1','1/2']] if variant and slot in ('crest4','crest8') else None
        p.add(slot,h,at,retime=retime,role='upper descending response')
    for slot,at in [('punctuation1',F(13,4)),('punctuation3',F(45,4)),('punctuation4',F(31,2)),('punctuation5',F(77,4)),('punctuation7',F(109,4)),('ending8',F(125,4))]:
        p.add(slot,c,at,duration=F(1,2) if slot!='punctuation4' else F(1,4),shift=-3 if variant and slot=='ending8' else 0,role='fixed B chord punctuation',legato=False)
    return p

def build_flow(m,variant=False):
    p=Phrase(132);f=m['flow'];g=m['hook'];h=m['high'];c=m['open_chord'];a=m['middle']
    # Retain the three-attack opening, then author a new answer from those
    # same contacts. The newly ordered intervals are recomputed, never labeled
    # as an unchanged observed eight-note motif.
    continuation=[0,1,2,4,5,7,6,1]
    for slot,at,shift in [('wave1',0,0),('wave2',4,0),('wave3',8,-3),('wave5',16,0),('wave6',20,-3)]:
        # Change two returning clocks while preserving corresponding attack identities.
        retime=None
        if variant and slot in ('wave3','wave6'):
            retime=[['0','1/4'],['1/4','1/2'],['3/4','1/4'],['1','1/4'],['5/4','1/4'],['3/2','1/2'],['2','1/4'],['9/4','1/4']]
        p.add(slot,f,at,shift=shift,retime=retime,order=continuation,role='open E / changing high excursion')
    for slot,at in [('low1',F(9,4)),('low5',F(73,4))]:p.add(slot,g,at,role='low reply',mute=True)
    p.add('crest2',h,F(25,4),role='descending answer')
    p.add('crest3',h,F(43,4) if variant else F(21,2),scale=F(1,2),role='short high reply')
    p.add('wave4a',f,12,prefix=3,role='opening recalled')
    p.add('punctuation4',c,F(53,4),duration=F(3,4),shift=-3,role='open B answer',legato=False)
    p.add('wave4b',f,F(29,2),prefix=5,order=continuation,role='abbreviated excursion')
    p.add('crest6',h,F(91,4) if variant else F(89,4),scale=F(1,2),role='short crest')
    p.add('wave7',f,24,prefix=5,order=continuation,shift=-3 if variant else 0,role='recognizable opening')
    p.add('crest7',h,F(51,2),role='upper reply')
    p.add('low7',g,F(109,4),prefix=2,role='two low pickup attacks',mute=True)
    p.add('wave8',f,28,prefix=5,order=continuation,shift=-3 if variant else 0,role='shortened final wave')
    p.add('punctuation8',c,F(59,2),duration=F(3,4),shift=-3,role='B/A punctuation',legato=False)
    p.add('last_answer',a,F(61,2),shift=5 if variant else 0,role='final open E return')
    return p

def build_chords(m,variant=False):
    p=Phrase(148);g=m['broken_hook'];c=m['open_chord'];s=m['shell']
    for slot,at,pre in [('call1',0,None),('call2',4,None),('call3',8,3),('call4',F(27,2),None),('call5',16,None),('call6',F(85,4),None),('call7',24,None)]:
        p.add(slot,g,at,prefix=pre,role='broken low call',mute=True)
    chords=[('a1',F(9,4),0,F(1,4)),('b1',F(13,4),-3,F(1,2)),('a2',6,0,F(1,2)),
            ('a3',F(39,4),0,F(3,4)),('b4',12,-3,1),('a4',F(31,2),0,F(1,4)),
            ('a5',F(73,4),0,F(1,4)),('b5',F(77,4),-3,F(1,2)),('a6',F(47,2),0,F(1,4)),
            ('a7',26,0,F(1,4)),('b7',F(107,4),-3,F(1,2)),('a8',28,0,F(1,2)),('b8',F(117,4),-3,F(3,4))]
    for slot,at,shift,dur in chords:
        if variant and slot in ('a5','a7','a8'):shift=-3
        if variant and slot in ('b5','b7','b8'):shift=0
        if variant and slot=='b8':at=F(119,4);dur=F(1,2)
        p.add(slot,c,at,shift=shift,duration=dur,role='B fixed / moving chord partner',legato=False)
    for slot,at,dur in [('shell2',7,F(3,4)),('shell3',11,F(1,2)),('shell6',20,F(3,4)),('shell7',F(55,2),F(1,2)),('shell8',31,F(3,4))]:
        p.add(slot,s,at,shift=5 if variant and slot in ('shell6','shell8') else 0,duration=dur,role='major-third / major-seventh shell',legato=False)
    return p

RECIPES = {
    "conversation": ("Fracture Dialogue", 142, build_conversation),
    "flow": ("Open Orbit", 132, build_flow),
    "chords": ("Glass Counterweight", 148, build_chords),
}


def generate(recipe="conversation", tempo=None):
    """Execute an existing recipe; return complete original/developed scores.

    The same recipe and tempo intentionally produce the same music. This MVP
    exposes the existing authored recipes, not a new randomized composer.
    """
    if not isinstance(recipe, str) or recipe not in RECIPES:
        raise ValueError("Choose conversation, flow, or chords")
    title, default_tempo, build = RECIPES[recipe]
    if tempo is None:
        tempo = default_tempo
    if isinstance(tempo, bool) or not isinstance(tempo, int) or not 80 <= tempo <= 200:
        raise ValueError("Tempo must be a whole number from 80 to 200 BPM")
    material = json.loads((Path(__file__).with_name("materials.json")).read_text(encoding="utf8"))
    baseline_phrase = build(material)
    variation_phrase = build(material, True)
    baseline_phrase.tempo = variation_phrase.tempo = tempo
    baseline = baseline_phrase.score()
    variation = variation_phrase.score()
    return {
        "title": title,
        "recipe": recipe,
        "tempo": tempo,
        "tuning": list(TUNING),
        "baseline": baseline,
        "variation": variation,
        "changes": final_differences(baseline, variation),
    }


def generate_json(recipe="conversation", tempo=None):
    return json.dumps(generate(recipe, tempo), separators=(",", ":"))
